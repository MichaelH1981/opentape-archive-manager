const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function translate(value) {
  if (language !== "en" || typeof value !== "string") return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, before, body, after] = match;
  if (en[body]) return before + en[body] + after;
  for (const [pattern, replacement] of patterns)
    if (pattern.test(body)) return before + body.replace(pattern, replacement) + after;
  if (body.includes(" · "))
    return before + body.split(" · ").map((part) => en[part] || translate(part)).join(" · ") + after;
  let translated = body;
  for (const [source, target] of fragments)
    translated = translated.replaceAll(source, target);
  if (translated !== body) return before + translated + after;
  return value;
}

function localize(root = document) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (["SCRIPT", "STYLE"].includes(node.parentElement?.tagName) || node.parentElement?.closest(".mono, .code-block, [data-no-i18n]")) continue;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const original = originalText.get(node);
    node.nodeValue = language === "en" ? translate(original) : original;
  }
  const elements = root.querySelectorAll ? [root, ...root.querySelectorAll("[placeholder], [aria-label], [title]")] : [];
  for (const element of elements) {
    if (!element.getAttribute || element.closest("[data-no-i18n]")) continue;
    let originals = originalAttributes.get(element);
    if (!originals) { originals = {}; originalAttributes.set(element, originals); }
    for (const attr of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute(attr)) continue;
      if (!(attr in originals)) originals[attr] = element.getAttribute(attr);
      element.setAttribute(attr, language === "en" ? translate(originals[attr]) : originals[attr]);
    }
  }
  document.documentElement.lang = language;
}

function setLanguage(value) {
  if (!["de", "en"].includes(value)) throw new Error("Unsupported language");
  language = value;
  try { localStorage.setItem("otam-language", value); } catch { /* Account setting remains authoritative. */ }
  localize(document);
}

